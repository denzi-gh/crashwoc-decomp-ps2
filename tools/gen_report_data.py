#!/usr/bin/env python3
"""Build objdiff's base objects for a data unit whose hybrid provides C data.

The unit's matching hybrid is linked at its addresses (as verify_promoted
does), and each owned range with no retail byte in it becomes a
`.split.<label>` section + symbol holding the linked bytes, the same layout
as its expected data object. Ranges with retail bytes are left out (0%).
A .sbss/.bss range counts when the hybrid places it (whole-unit mode only):
its NOBITS section carries no bytes, verify_promoted checks its objects'
addresses. Each `[[claim]]` span gets its own base object,
report-data/unassigned/<label>.o, the target being the claimed gap's piece
(gen_data_objects.split_claims).

Needs the PS2 binutils (`ninja report-data`). Output: build/<v>/report-data/.
"""
import argparse
import json
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from gen_data_objects import (NOBITS_SECTIONS, load_map, range_section,
                              section_label)
from gen_hybrid import data_report_path, manifest_claims, provides_data

_HEADER = ("/* Generated by tools/gen_report_data.py -- do not edit, do not "
           "commit (game-derived). */\n")


def report_data_units(version):
    """[(stem, manifest, complete)] for units with C data and a data unit
    (an owned range or a claimed span).

    `stem` is `unit-NNNN`, `manifest` a repo-relative POSIX path. Pure."""
    owners = {r["owner"] for r in load_map(version)}
    out = []
    status_dir = ROOT / "config" / version / "status"
    if status_dir.is_dir():
        for m in sorted(status_dir.rglob("*.toml")):
            data = tomllib.loads(m.read_text())
            stem = data["unit"].split(":")[1]
            if (stem in owners or data.get("claim")) and provides_data(data):
                out.append((stem, m.relative_to(ROOT).as_posix(),
                            bool(data.get("complete"))))
    return out


def claim_stem(section, start):
    """Data-object stem of a claimed span (its expected piece and base)."""
    return f"unassigned/{section_label({'section': section, 'start': start})}"


def c_ranges(ranges, pieces, retail):
    """[(range, piece)] for owned ranges a piece covers exactly with no
    retail span ([lo, hi)) overlapping them."""
    by_span = {(p["section"], p["start"], p["end"]): p for p in pieces}
    out = []
    for r in sorted(ranges, key=lambda r: r["start"]):
        piece = by_span.get((r["section"], r["start"], r["end"]))
        if piece is None:
            continue
        if any(lo < r["end"] and r["start"] < hi for lo, hi in retail):
            continue
        out.append((r, piece))
    return out


def claim_pieces(claims, pieces):
    """[(span, piece)] for the manifest's claims, each the piece of exactly
    that span (a stale hybrid without one fails)."""
    by_span = {(p["section"], p["start"], p["end"]): p for p in pieces}
    out = []
    for section, start, end in claims:
        piece = by_span.get((section, start, end))
        if piece is None:
            raise SystemExit(f"claim {section} 0x{start:08x}-0x{end:08x}: "
                             "no hybrid piece (rebuild the matching hybrid)")
        out.append(({"section": section, "start": start, "end": end}, piece))
    return out


def _assemble(as_bin, s_path, out_o):
    out_o.parent.mkdir(parents=True, exist_ok=True)
    try:
        subprocess.run([as_bin, "-EL", "-march=r5900", "-o", str(out_o),
                        str(s_path)], check=True, capture_output=True,
                       text=True)
    except subprocess.CalledProcessError as exc:
        raise SystemExit(f"{s_path.stem}: as failed: "
                         f"{(exc.stderr or '').strip().splitlines()[:2]}")


def build_report_data(manifest, out_o, version="pal103"):
    """Write one unit's base object and its claims' base objects (next to
    it, under unassigned/); returns (ranges from C, owned ranges, claims)."""
    from declib.asmtext import load_symbol_addrs, resolve
    from declib.toolchain import AS, LD, NM, tool_path
    from declib.verify import (defined_function_offsets, link_unit_at,
                               undefined_externals)
    from verify_promoted import function_sizes

    as_bin, nm_bin = tool_path(AS), tool_path(NM)
    if not (as_bin and nm_bin and tool_path(LD)):
        raise SystemExit("PS2 binutils not found; run in the Containerfile "
                         "image.")
    manifest = Path(manifest)
    out_o = Path(out_o)
    data = tomllib.loads(manifest.read_text())
    stem = data["unit"].split(":")[1]
    unit_index = int(stem.split("-")[1])
    rel = Path(data["source"]).relative_to("src").with_suffix(".o")
    hybrid_o = ROOT / "build" / version / "matching" / rel
    sidecar = data_report_path(hybrid_o)
    if not provides_data(data) or not sidecar.is_file():
        raise SystemExit(f"{manifest}: no C data (or {sidecar} missing; "
                         f"build the matching hybrid first).")
    report = json.loads(sidecar.read_text())
    ranges = [r for r in load_map(version) if r["owner"] == stem]
    chosen = c_ranges(ranges, report["pieces"], report.get("retail", []))
    claimed = claim_pieces(manifest_claims(data), report["pieces"])

    linked = {}
    if any(r["section"] not in NOBITS_SECTIONS for r, _p in chosen + claimed):
        # Same link as verify_promoted.
        sizes = function_sizes(version).get(unit_index, {})
        offsets = defined_function_offsets(nm_bin, hybrid_o)
        starts = [sizes[n][0] for n in offsets if n in sizes]
        if not starts:
            raise SystemExit(f"{hybrid_o}: no registry function to place "
                             ".text at")
        undef = undefined_externals(nm_bin, hybrid_o)
        defsyms, unresolved = resolve(sorted(undef - {"_gp"}),
                                      load_symbol_addrs(version))
        if unresolved:
            raise SystemExit(f"{hybrid_o}: unresolved externals "
                             f"{unresolved[:4]}")
        with tempfile.TemporaryDirectory() as tmp:
            _text, linked, _syms = link_unit_at(
                hybrid_o, min(starts), report["pieces"], defsyms, Path(tmp))

    work = out_o.parent / f"{out_o.stem}_s"
    work.mkdir(parents=True, exist_ok=True)

    def section(r, piece):
        label = section_label(r)
        size = r["end"] - r["start"]
        if r["section"] in NOBITS_SECTIONS:
            return range_section(label, None, size)
        blob = linked[piece["name"]]
        if len(blob) != size:
            raise SystemExit(f"{piece['name']}: linked {len(blob)} bytes, "
                             f"range is {size}")
        bin_path = work / f"{label}.bin"
        bin_path.write_bytes(blob)
        return range_section(label, bin_path, size)

    s_path = work / f"{stem}.s"
    s_path.write_text(_HEADER + "".join(section(r, p) for r, p in chosen))
    _assemble(as_bin, s_path, out_o)
    for r, piece in claimed:
        s_path = work / f"{section_label(r)}.s"
        s_path.write_text(_HEADER + section(r, piece))
        _assemble(as_bin, s_path,
                  out_o.parent / f"{claim_stem(r['section'], r['start'])}.o")
    return len(chosen), len(ranges), len(claimed)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--manifest", required=True,
                        help="status manifest of the unit")
    parser.add_argument("-o", "--output", required=True,
                        help="base object to write")
    parser.add_argument("--version", default="pal103")
    args = parser.parse_args()

    n_c, n_all, n_claims = build_report_data(args.manifest, args.output,
                                             args.version)
    print(f"{args.output}: {n_c}/{n_all} owned range(s) from C"
          + (f", {n_claims} claimed span(s)" if n_claims else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
